import assert from 'node:assert/strict';
import {analyzePixels,candidateStatus,detectPlatform,profileFor,csvValue} from '../matrix-core.mjs';
const samples={width:2,height:1,text:[0],background:[1]};
assert.equal(analyzePixels(new Uint8ClampedArray([255,255,255,255,255,255,255,255]),samples).shot_delta_y,0);
assert.ok(Math.abs(analyzePixels(new Uint8ClampedArray([255,255,255,255,0,0,0,255]),samples).shot_delta_y-255)<1e-9);
const env={capture_mode:'SDR',screenshot_hdr:'no',hdr_enabled:'yes',ab_difference:'yes'};
const cell={bg_nit:203,text_nit:500,screen_score:4,delta_threshold:2,zoom_readable:'no',enhanced_readable:'no',analysis:{shot_delta_y:0,original_sdr_confirmed:true,mode:'hdr'}};
assert.ok(candidateStatus(cell,env).startsWith('候选'));
assert.ok(!candidateStatus(cell,{...env,capture_mode:'HDR'}).startsWith('候选'));
assert.ok(!candidateStatus({...cell,screen_score:0},env).startsWith('候选'));
assert.ok(!candidateStatus({...cell,text_nit:203},env).startsWith('候选'));
assert.ok(!candidateStatus({...cell,analysis:null},env).startsWith('候选'));
assert.ok(!candidateStatus({...cell,zoom_readable:'unknown'},env).startsWith('候选'));
assert.ok(!candidateStatus({...cell,analysis:{...cell.analysis,mode:'standard'}},env).startsWith('候选'));
assert.ok(!candidateStatus({...cell,analysis:{...cell.analysis,shot_delta_y:4}},env).startsWith('候选'));
assert.equal(detectPlatform('Mozilla/5.0 (Linux; Android 10; K)'), 'Android');
assert.ok(profileFor({platform:'Android',os_version:''}).includes('待确认'));
assert.ok(profileFor({platform:'Android',os_version:'Android 15'}).includes('Android 15'));
assert.equal(csvValue('=1+1'),'"\'=1+1"');
console.log('PASS: luminance, candidate exclusions, unknown Android versions, CSV escaping.');
